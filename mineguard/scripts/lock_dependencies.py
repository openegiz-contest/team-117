"""Add official PyPI release SHA256 hashes to pip-compile's resolved pins.

Avoid downloading wheels for every supported platform just to hash them.
Install the resulting lock with pip --require-hashes. Only public PyPI pins
are supported; unexpected directives, URLs, markers or unpinned lines fail.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import re
import urllib.request

PIN = re.compile(r"([A-Za-z0-9][A-Za-z0-9_.-]*)==([A-Za-z0-9_.!+\-]+)")


def release_hashes(pin: str) -> str:
    name, version = pin.split("==")
    request = urllib.request.Request(
        f"https://pypi.org/pypi/{name}/{version}/json",
        headers={"Accept": "application/json", "User-Agent": "MineGuard-lock/1"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        release = json.load(response)
    normalize = lambda value: re.sub(r"[-_.]+", "-", value).lower()
    if (normalize(release["info"]["name"]) != normalize(name)
            or release["info"]["version"] != version):
        raise ValueError(f"Unexpected release metadata for {pin}")
    hashes = sorted({item["digests"]["sha256"] for item in release["urls"]
                     if not item.get("yanked", False)})
    if not hashes or any(not re.fullmatch(r"[0-9a-f]{64}", value) for value in hashes):
        raise ValueError(f"No valid distribution hashes for {pin}")
    return pin + " " + " ".join("--hash=sha256:" + value for value in hashes)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("lock", type=Path)
    args = parser.parse_args()
    pins = []
    for line in args.lock.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("--hash="):
            continue
        line = line.removesuffix(chr(92)).strip()
        # Also accept this tool's previously hashed, single-line output.
        candidate = line.split(" --hash=", 1)[0]
        if not PIN.fullmatch(candidate):
            raise ValueError("Lock input contains an unsupported or unpinned requirement")
        pins.append(candidate)
    if not pins or len(set(pin.split("==")[0].lower() for pin in pins)) != len(pins):
        raise ValueError("Empty or duplicate dependency pins")
    with ThreadPoolExecutor(max_workers=4) as executor:
        entries = list(executor.map(release_hashes, sorted(pins)))
    header = ("# Resolved by pip-compile; hashes from official PyPI release JSON.\n"
              "# Generated by mineguard/scripts/lock_dependencies.py.\n"
              "# Install using pip --require-hashes; do not edit manually.\n")
    # Do not touch the original file unless every release validated.
    args.lock.write_text(header + "\n".join(entries) + "\n", encoding="utf-8")
    print(f"Verified official release hashes for {len(entries)} pinned dependencies")


if __name__ == "__main__":
    main()
